-- Helper function: checks current user's role without exposing passwords/secrets.
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

-- Public services/settings
create policy "services public read" on services for select using (active = true or public.is_admin());
create policy "services admin all" on services for all using (public.is_admin()) with check (public.is_admin());

create policy "settings public read" on settings for select using (true);
create policy "settings admin all" on settings for all using (public.is_admin()) with check (public.is_admin());

-- Profile
create policy "profile own read" on profiles for select using (auth.uid() = id or public.is_admin());
create policy "profile own update" on profiles for update using (auth.uid() = id or public.is_admin()) with check (auth.uid() = id or public.is_admin());

-- Orders
create policy "orders own read" on orders for select using (auth.uid() = user_id or public.is_admin());
create policy "orders own insert" on orders for insert with check (auth.uid() = user_id);
create policy "orders admin update" on orders for update using (public.is_admin()) with check (public.is_admin());

-- Deposits
create policy "deposits own read" on deposits for select using (auth.uid() = user_id or public.is_admin());
create policy "deposits own insert" on deposits for insert with check (auth.uid() = user_id);
create policy "deposits admin update" on deposits for update using (public.is_admin()) with check (public.is_admin());

-- Transactions
create policy "transactions own read" on transactions for select using (auth.uid() = user_id or public.is_admin());
create policy "transactions admin insert" on transactions for insert with check (public.is_admin());

-- Feedback
create policy "feedback visible read" on feedback for select using (visible = true or auth.uid() = user_id or public.is_admin());
create policy "feedback own insert" on feedback for insert with check (auth.uid() = user_id);
create policy "feedback admin update" on feedback for update using (public.is_admin()) with check (public.is_admin());

-- Notifications
create policy "notifications own read" on notifications for select using (auth.uid() = user_id or public.is_admin());
create policy "notifications own update" on notifications for update using (auth.uid() = user_id or public.is_admin()) with check (auth.uid() = user_id or public.is_admin());
create policy "notifications admin insert" on notifications for insert with check (public.is_admin());

-- Logs
create policy "logs admin read" on admin_logs for select using (public.is_admin());
create policy "logs admin insert" on admin_logs for insert with check (public.is_admin());

-- Trigger profile creation after signup
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles(id, username, display_name)
  values (
    new.id,
    split_part(coalesce(new.email, new.id::text), '@', 1),
    split_part(coalesce(new.email, new.id::text), '@', 1)
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

