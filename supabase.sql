-- PLAYTOGETHER SHOP - SUPABASE SCHEMA
create extension if not exists pgcrypto;

create table if not exists profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  display_name text,
  role text not null default 'customer' check (role in ('customer','admin')),
  balance bigint not null default 0 check (balance >= 0),
  created_at timestamptz not null default now()
);

create table if not exists services (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text unique not null,
  description text,
  price bigint not null default 0 check (price >= 0),
  active boolean not null default true,
  image_url text,
  created_at timestamptz not null default now()
);

create table if not exists orders (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  service_id bigint references services(id) on delete set null,
  game_id text,
  character_name text,
  contact text,
  note text,
  quantity int not null default 1 check (quantity > 0),
  unit_price bigint not null default 0 check (unit_price >= 0),
  total bigint not null default 0 check (total >= 0),
  status text not null default 'pending'
    check (status in ('pending','processing','doing','completed','cancelled')),
  admin_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists deposits (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  amount bigint not null check (amount > 0),
  transfer_code text not null,
  proof_url text,
  status text not null default 'pending'
    check (status in ('pending','approved','rejected')),
  admin_note text,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);

create table if not exists transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  amount bigint not null,
  type text not null check (type in ('deposit','order','refund','adjustment')),
  reference_id bigint,
  note text,
  created_at timestamptz not null default now()
);

create table if not exists feedback (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  order_id bigint references orders(id) on delete set null,
  rating int not null check (rating between 1 and 5),
  content text,
  visible boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  message text not null,
  read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists settings (
  key text primary key,
  value text not null,
  updated_at timestamptz not null default now()
);

create table if not exists admin_logs (
  id bigint generated by default as identity primary key,
  admin_id uuid references auth.users(id) on delete set null,
  action text not null,
  target_type text,
  target_id bigint,
  details jsonb,
  created_at timestamptz not null default now()
);

create index if not exists orders_user_id_idx on orders(user_id);
create index if not exists orders_status_idx on orders(status);
create index if not exists deposits_user_id_idx on deposits(user_id);
create index if not exists deposits_status_idx on deposits(status);
create index if not exists transactions_user_id_idx on transactions(user_id);
create index if not exists notifications_user_id_idx on notifications(user_id);

